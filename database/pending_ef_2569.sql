-- ───────────────────────────────────────────────────────────────────────
-- ส่วนที่ 3 — ลบ "ก๊าซชีวภาพ" ออกจากหมวดการเผาไหม้เคลื่อนที่ On Road
--
-- เอกสาร อบก. มี Biogas เฉพาะหมวด Stationary หน่วย m3 ค่า 0.0011 เท่านั้น
-- ไม่มีค่าสำหรับยานพาหนะ และค่า 0.0084 kg ที่อยู่ในระบบหาที่มาไม่ได้
-- (รายการ Stationary id=37 ยังคงไว้ ค่า 0.0011 ตรงเอกสารแล้ว)
-- ───────────────────────────────────────────────────────────────────────
SELECT id, name_tiem, unit, AD,
       (SELECT COUNT(*) FROM user_item u WHERE u.admin_item_id = admin_item.id) AS อ้างอิง
